package Rectangulo;

public class Rectangulo {

	private int base;
	private int altura;
	
	
	public Rectangulo(int altura, int base) {
		this.altura=altura;
		this.base=base;
		
	}public int getAltura() {
		return altura;
	}public void setAltura(int altura) {
		this.altura=0;
	}public int getBase() {
		return base;
	}public void setBase(int base) {
		this.base=0;
	}
	
}
